"""Real-site celestial study and regression. Requires Python Playwright.

--prepare-study creates an uncommitted Next route using the production component
and root layout. --clean-study removes only that generated route after review.
"""
import argparse
from datetime import datetime
import json
from pathlib import Path
import re
import sys

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--url', default='http://127.0.0.1:3119')
parser.add_argument('--output', default='.sync/tmp-celestial')
parser.add_argument('--browser')
parser.add_argument('--prepare-study', action='store_true')
parser.add_argument('--clean-study', action='store_true')
parser.add_argument('--checks-only', action='store_true')
parser.add_argument('--record-only', action='store_true', help='Capture hover/focus/switch video and editable SVG states')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
fixture = root / 'app/celestial-study/page.tsx'
marker = '// Generated by celestial-preview.py; never deploy this study route.'
if args.prepare_study or args.clean_study:
    if fixture.exists() and not fixture.read_text(encoding='utf-8').startswith(marker):
        raise RuntimeError('Refusing to change a route not generated by this script')
    if args.clean_study:
        fixture.unlink(missing_ok=True)
        if fixture.parent.exists():
            fixture.parent.rmdir()
    else:
        fixture.parent.mkdir(parents=True, exist_ok=True)
        fixture.write_text(marker + '''
import HomeCelestialControl from "../../components/HomeCelestialControl"
export const metadata = { robots: { index: false, follow: false } }
export default function CelestialStudy() {
  return <main data-celestial-study style={{ minHeight: "100dvh" }}><HomeCelestialControl /></main>
}
''', encoding='utf-8')
    print('Study route prepared' if args.prepare_study else 'Study route removed')
    sys.exit(0)

from playwright.sync_api import sync_playwright, expect

out = Path(args.output).resolve()
out.mkdir(parents=True, exist_ok=True)
checks = []
errors = []

def visit(page, path='/celestial-study'):
    response = page.goto(args.url + path, wait_until='domcontentloaded', timeout=60000)
    assert response and response.ok, f'{path}: no successful response'
    page.wait_for_function("document.documentElement.classList.contains('splash-seen')")
    page.wait_for_load_state('networkidle')

def celestial(page):
    return page.locator('[data-home-celestial]')

def settings(page):
    trigger = page.get_by_role('button', name='显示设置', exact=True)
    if trigger.get_attribute('aria-expanded') != 'true':
        trigger.click()
    expect(page.get_by_role('group', name='显示设置选项')).to_be_visible()
    return page.get_by_role('group', name='显示设置选项')

def modes(page, dark, field):
    if celestial(page).get_attribute('aria-pressed') != str(dark).lower():
        celestial(page).click()
    mode = settings(page).get_by_role('button', name=re.compile('当前(常规|谱场)'))
    if mode.get_attribute('aria-pressed') != str(field).lower():
        mode.click()
    expect(celestial(page)).to_have_attribute('aria-pressed', str(dark).lower())
    page.keyboard.press('Escape')
    page.get_by_role('button', name='显示设置', exact=True).evaluate('el => el.blur()')
    page.wait_for_timeout(1150)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, **({'executable_path': args.browser} if args.browser else {}))
    if args.record_only:
        recording = browser.new_context(viewport={'width':1440,'height':900}, timezone_id='Asia/Shanghai',
                                        record_video_dir=str(out/'video'), record_video_size={'width':1440,'height':900})
        recording.add_init_script("localStorage.setItem('blog-theme','light'); localStorage.setItem('blog-theme-override-until',String(Date.now()+86400000))")
        page = recording.new_page()
        visit(page)
        button = celestial(page)
        for dark, name in [(False,'sun'),(True,'moon')]:
            if button.get_attribute('aria-pressed') != str(dark).lower():
                button.click()
            page.wait_for_timeout(1200)
            source = button.locator('svg').evaluate("""svg => {
                const copy=svg.cloneNode(true);
                const original=svg.querySelectorAll('*'), cloned=copy.querySelectorAll('*');
                original.forEach((node,i)=>{
                    const css=getComputedStyle(node);
                    if(node.tagName.toLowerCase()==='g') cloned[i].setAttribute('style',`opacity:${css.opacity};transform:${css.transform};transform-origin:${css.transformOrigin}`);
                    cloned[i].removeAttribute('class');
                });
                copy.setAttribute('xmlns','http://www.w3.org/2000/svg');
                copy.setAttribute('width','128'); copy.setAttribute('height','128');
                copy.removeAttribute('class'); copy.removeAttribute('aria-hidden');
                return copy.outerHTML;
            }""")
            (out/(name+'.svg')).write_text(source,encoding='utf-8')
            button.hover()
            page.wait_for_timeout(650)
            page.screenshot(path=str(out/(name+'-hover.jpg')),type='jpeg',quality=90)
            button.focus()
            page.keyboard.press('Tab')
            page.keyboard.press('Shift+Tab')
            page.wait_for_timeout(400)
            page.screenshot(path=str(out/(name+'-focus.jpg')),type='jpeg',quality=90)
        button.click()
        page.wait_for_timeout(1200)
        video=page.video
        recording.close()
        video.save_as(str(out/'theme-switch.webm'))
        browser.close()
        print('Recorded hover/focus/day-night switch and exported SVG states',flush=True)
        sys.exit(0)
    context = browser.new_context(viewport={'width': 1440, 'height': 900}, timezone_id='Asia/Shanghai')
    page = context.new_page()
    page.on('pageerror', lambda error: errors.append(str(error)))
    visit(page, '/')
    assert page.get_by_role('button', name=re.compile('昼夜交替|性能交替')).count() == 0
    assert page.locator('[data-home-celestial]').count() == 1
    page.screenshot(path=str(out / 'home-integration.jpg'), type='jpeg', quality=85)
    visit(page)
    for width, height in ([] if args.checks_only else [(1440,900),(1280,800),(1024,768)]):
        page.set_viewport_size({'width': width, 'height': height})
        for dark, field in [(False,False),(False,True),(True,False),(True,True)]:
            modes(page, dark, field)
            b = celestial(page).bounding_box()
            assert b and b['width'] >= 48 and b['height'] >= 48
            assert b['x'] >= 0 and b['x'] + b['width'] <= width
            nav = page.get_by_role('navigation', name='主导航').bounding_box()
            assert b['y'] > nav['y'] + nav['height'], 'Celestial hitbox overlaps navigation'
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
            page.screenshot(path=str(out / f'scene-{width}-{"night" if dark else "day"}-{"field" if field else "normal"}.jpg'), type='jpeg', quality=90)
        print(f'PASS {width}x{height} four combinations / real root layout', flush=True)
    modes(page, False, False)
    start = page.evaluate('performance.timeOrigin')
    celestial(page).focus()
    page.keyboard.press('Enter')
    expect(celestial(page)).to_have_attribute('aria-pressed', 'true')
    assert celestial(page).evaluate("el => getComputedStyle(el).outlineStyle") != 'none'
    page.screenshot(path=str(out / 'celestial-focus.jpg'), type='jpeg', quality=85)
    page.keyboard.press('Space')
    expect(celestial(page)).to_have_attribute('aria-pressed', 'false')
    assert page.evaluate('performance.timeOrigin') == start, 'Theme triggered a navigation/reload'
    assert page.evaluate("localStorage.getItem('blog-performance-mode')") in [None, 'normal']
    settings(page).get_by_role('button', name=re.compile('当前常规')).click()
    assert celestial(page).get_attribute('aria-pressed') == 'false'
    page.screenshot(path=str(out / 'settings-expanded.jpg'), type='jpeg', quality=85)
    page.keyboard.press('Escape')
    page.reload()
    visit(page)
    expect(settings(page).get_by_role('button', name=re.compile('当前谱场'))).to_be_visible()
    other = context.new_page()
    visit(other)
    settings(other).get_by_role('button', name=re.compile('当前谱场')).click()
    expect(settings(page).get_by_role('button', name=re.compile('当前常规'))).to_be_visible()
    other.close()
    page.evaluate("localStorage.setItem('blog-performance-mode','field'); window.dispatchEvent(new Event('field-mode-change'))")
    expect(settings(page).get_by_role('button', name=re.compile('当前谱场'))).to_be_visible()
    page.keyboard.press('Escape')
    page.emulate_media(reduced_motion='reduce')
    modes(page, True, True)
    assert celestial(page).evaluate("el => el.getAnimations({subtree:true}).every(a => a.playState !== 'running')")
    page.screenshot(path=str(out / 'reduced-motion.jpg'), type='jpeg', quality=85)
    assert page.locator('canvas').count() == 0, 'Controls unexpectedly mount a renderer'
    checks.append('keyboard/focus; independent states; no reload; persistence; storage/custom-event sync; reduced motion; no canvas')
    print('PASS desktop interactions and storage', flush=True)
    context.close()

    for width in [320,390]:
        mobile = browser.new_context(viewport={'width':width,'height':844}, is_mobile=True, has_touch=True, reduced_motion='reduce')
        page = mobile.new_page()
        visit(page, '/about')
        assert celestial(page).count() == 0
        trigger = page.get_by_role('button', name='显示设置', exact=True)
        trigger.tap()
        group = page.get_by_role('group', name='显示设置选项')
        theme = group.get_by_role('button', name=re.compile('当前(日间|夜间)'))
        before = theme.get_attribute('aria-pressed')
        theme.tap()
        expect(theme).not_to_have_attribute('aria-pressed', before)
        group.get_by_role('button', name=re.compile('当前(常规|谱场)')).tap()
        bounds = group.bounding_box()
        back = page.get_by_role('button', name='返回上一页').bounding_box()
        assert bounds['x'] >= 0 and bounds['x']+bounds['width'] <= width
        if back:
            assert bounds['x']+bounds['width'] < back['x']
        page.screenshot(path=str(out / f'inner-page-touch-{width}.jpg'), type='jpeg', quality=85)
        page.keyboard.press('Escape')
        expect(trigger).to_have_attribute('aria-expanded','false')
        mobile.close()
    checks.append('320/390px inner-page touch, theme access, menu/back-button separation')
    print('PASS mobile inner pages', flush=True)

    timed = browser.new_context(viewport={'width':1440,'height':900}, timezone_id='Asia/Shanghai')
    page = timed.new_page()
    page.clock.install(time=datetime.fromisoformat('2026-11-05T05:50:00+08:00'))
    visit(page)
    expect(celestial(page)).to_have_attribute('aria-pressed','true')
    def advance(iso):
        page.clock.fast_forward(int(datetime.fromisoformat(iso).timestamp()*1000)-page.evaluate('Date.now()'))
    advance('2026-11-05T06:00:00.200+08:00')
    expect(celestial(page)).to_have_attribute('aria-pressed','false')
    celestial(page).click()
    page.reload()
    visit(page)
    expect(celestial(page)).to_have_attribute('aria-pressed','true')
    celestial(page).click()
    advance('2026-11-05T18:00:00.200+08:00')
    expect(celestial(page)).to_have_attribute('aria-pressed','true')
    assert page.evaluate("localStorage.getItem('blog-theme-override-until')") is None
    checks.append('06:00/18:00 boundaries, manual override/reload/expiry')
    timed.close()
    browser.close()
(out / 'report.json').write_text(json.dumps({'checks':checks,'pageErrors':errors},ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({'checks':checks,'pageErrors':errors},ensure_ascii=False),flush=True)
